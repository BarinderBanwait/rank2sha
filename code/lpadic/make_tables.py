#!/usr/bin/env python3
"""make_tables.py -- build the two A5 deliverable tables from the committed outputs.

Reads   ../data/cert_<p>.out   (produced by run.sh)
        ../data/hypotheses.out (produced by hypotheses.sage)
        ../data/lmfdb_iwasawa.txt
Writes  ../data/tables.md

Table (i)  the six-row hypothesis table for prop:consequence.
Table (ii) eq:match5 extended from two primes to six: height side against L-side,
           digit for digit.
Table (iii) in-house lambda_an/mu_an against Appendix B (LMFDB).
Table (iv) the certificates in the frozen Certificates.lean shape.

MISSING IS NOT DISAGREEING.  A prime with no cert_<p>.out on disk has not been
computed; it reads "not computed" everywhere and it must NEVER raise the
stop-the-line signal.  The stop-the-line signal is reserved for the two events
that actually are one: an in-house lambda/mu that DIFFERS from Appendix B, and a
computed height side that DIFFERS from the computed L-side.  A signal that fires
on a gap is a signal nobody reads.

No number in docs/A5_REPORT.md is typed by hand; they are all copied from this
file, which is generated from the raw outputs.

Usage:  python3 make_tables.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
PRIMES = [5, 13, 17, 29, 37, 41]

MLINE = re.compile(r"MACHINE\s+(\S+)\s+v=\s*(-?\d+)\s+prec=\s*(-?\d+)\s+digits=\[([^\]]*)\]")
HYP = re.compile(r"MACHINE hyp p=(\d+) (.*)$")


def read_machine(path):
    out = {}
    if not os.path.exists(path):
        return out
    with open(path) as fh:
        for ln in fh:
            m = MLINE.search(ln)
            if m:
                out[m.group(1)] = (
                    int(m.group(2)), int(m.group(3)),
                    [int(x) for x in m.group(4).replace(" ", "").split(",") if x],
                )
    return out


def read_scalar(path, key):
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        for ln in fh:
            if ln.startswith(key):
                return ln.split(":", 1)[1].strip()
    return None


hyp = {}
hp = os.path.join(DATA, "hypotheses.out")
if os.path.exists(hp):
    with open(hp) as fh:
        for ln in fh:
            m = HYP.search(ln)
            if m:
                d = dict(kv.split("=", 1) for kv in m.group(2).split())
                hyp[int(m.group(1))] = d

lmfdb = {}
lmfdb_rows = []          # every row of the table, in file order: (p, reduction, lam, mu)
lp = os.path.join(DATA, "lmfdb_iwasawa.txt")
if os.path.exists(lp):
    with open(lp) as fh:
        for ln in fh:
            if ln.startswith("#") or not ln.strip():
                continue
            f = ln.split()
            if len(f) >= 4 and f[0].isdigit():
                lmfdb[int(f[0])] = (f[2], f[3])
                lmfdb_rows.append((int(f[0]), f[1], f[2], f[3]))

cert = {}
meta = {}
for p in PRIMES:
    path = os.path.join(DATA, "cert_%d.out" % p)
    cert[p] = read_machine(path)
    meta[p] = {
        "file": "cert_%d.out" % p,
        "exists": os.path.exists(path),
        "n": read_scalar(path, "n (approx order)"),
        "summands": (read_scalar(path, "summands in the Riemann sum") or "").split("=")[-1].strip() or None,
        "runtime": read_scalar(path, "series runtime"),
        "c2prec": read_scalar(path, "c_2 precision"),
        "c0prec": read_scalar(path, "c_0 precision"),
        "c1prec": read_scalar(path, "c_1 precision"),
        "cbound": read_scalar(path, "_c_bound()"),
        "bounds": read_scalar(path, "_prec_bounds(n,precT)"),
        "date": read_scalar(path, "date            "),
        "result": read_scalar(path, "RESULT          "),
        "Lp": read_scalar(path, "L_p(E,T)"),
        "impl": read_scalar(path, "implementation    "),
    }

