# ==================================================================
#  LaTeX emitter -- the same numbers, in the shape the Paper I
#  fragments use.  The fragments must be SELF-CONTAINED (they cannot
#  \input this file), so the blocks below are pasted into
#  paper1-sha/fragments/*.tex between BEGIN/END GENERATED markers.
#  Re-run this script and re-paste after any precision upgrade; that
#  is the only hand step, and it copies, it does not retype.
# ==================================================================

def padic_tex(v, digits, p, k):
    r"""base-p expansion as LaTeX, e.g. 1 + 4\cdot 5 + 3\cdot 5^2 + O(5^7)."""
    terms = []
    for j, dj in enumerate(digits):
        e = v + j
        if dj == 0:
            continue
        if e == 0:
            terms.append("%d" % dj)
        elif e == 1:
            terms.append(("%d\\cdot %d" % (dj, p)) if dj != 1 else "%d" % p)
        else:
            terms.append(("%d\\cdot %d^{%d}" % (dj, p, e)) if dj != 1
                         else "%d^{%d}" % (p, e))
    body = " + ".join(terms) if terms else "0"
    return "%s + O(%d^{%d})" % (body, p, k)


